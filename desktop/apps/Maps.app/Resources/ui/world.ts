/**
 * The Pear World: an equirectangular projection of the real Earth, drawn as a few hand-made blobs.
 * Lon/lat go in, world units come out (4 px per degree); nobody charts shipping routes with this.
 */

export const WORLD_W = 1440 // 4 px per degree of longitude (360 * 4)
export const WORLD_H = 720 // 4 px per degree of latitude (180 * 4)

/** World-unit x for a longitude (°E positive, °W negative, ±180 at the edges). */
export const px = (lon: number): number => ((lon + 180) / 360) * WORLD_W
/** World-unit y for a latitude (°N positive). */
export const py = (lat: number): number => ((90 - lat) / 180) * WORLD_H

/** A hand-authored outline, as `[lon°E, lat°N]` corners walking around the blob. */
export type Poly = Array<[number, number]>

const Polygon = (name: string, ...pts: Poly): { name: string; pts: Poly } => ({ name, pts })

