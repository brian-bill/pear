// Generates the checked-in, generated sources of the Code app. Run from `desktop/`:
//
//   node apps/Code.app/tools/generate.mjs
//
// - `asc.js`: the AssemblyScript compiler (`asc`, with its embedded Binaryen wasm)
//   bundled as a module worker. At runtime the Code app reads this file from its own
//   bundle and runs it as a blob worker, compiling AssemblyScript to WebAssembly
//   entirely in the browser — no server, no toolchain on the user's machine.
import { build } from 'esbuild'
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '../Resources/ui/asc.js')

const r = await build({
  entryPoints: [join(here, 'compiler.worker.js')],
  bundle: true,
  write: false,
  format: 'esm',
  target: 'es2022',
  platform: 'browser',
  minify: true,
  logLevel: 'warning',
  define: { 'globalThis.process': 'undefined', process: 'undefined' },
  // dead node-only branches (`typeof process` checks) still get resolved; a stub keeps them resolvable but inert
  alias: {
    fs: join(here, 'noop.js'),
    module: join(here, 'noop.js'),
    path: join(here, 'noop.js'),
    url: join(here, 'noop.js'),
    'node:module': join(here, 'noop.js'),
  },
})
const source = r.outputFiles[0].text
// The ESM bundle uses top-level await and import.meta.url — both illegal in a classic worker
// script. Wrapping it in an async IIFE makes the await legal; import.meta.url only feeds
// node-style paths here, so a dummy URL is fine. The prelude queues worker messages until the
// (asynchronously initialising) compiler has installed its real handler.
const body = source.replaceAll('import.meta.url', '"file:///asc.js"')
const wrapped = [
  '/* GENERATED by tools/generate.mjs — do not edit. The AssemblyScript compiler (with its embedded',
  '   Binaryen wasm) as a classic worker: the Code app reads this file from its own bundle and runs it',
  '   as a blob worker to compile AssemblyScript sources to WebAssembly in the browser. */',
  'var __pearQueue = []',
  'self.onmessage = (e) => { __pearQueue.push(e) }',
  "const __of = self.fetch",
  "self.fetch = (u, o) => { u = String(u); if (u.startsWith('data:')) { const i = u.indexOf(','); const meta = u.slice(5, i).split(';')[0]; const s = atob(u.slice(i + 1)); const b = new Uint8Array(s.length); for (let j = 0; j < s.length; j++) b[j] = s.charCodeAt(j); return Promise.resolve(new Response(b, { headers: { 'Content-Type': meta } })) } return __of(u, o) }",
  ';(async () => {',
  body,
  'if (typeof __pearDrain === "function") { const q = __pearQueue.splice(0); for (const e of q) __pearDrain(e) }',
  '})().catch((e) => self.postMessage({ id: 0, ok: false, log: "compiler init: " + ((e && e.message) || e) }))',
].join('\n')
// Written as a plain bundle file (not imported by the app's script): it stays out of the
// window document and is read on demand with `tiny.readFile` — apps may read their own bundle.
writeFileSync(out, wrapped)
console.log(`asc.js: ${(wrapped.length / 1e6).toFixed(1)} MB`)

// ---- Monaco's language services -------------------------------------------------------------
// IntelliSense, diagnostics, formatting and colour decorators for TypeScript/JavaScript, CSS/SCSS/
// Less, HTML and JSON run in Monaco's own workers. Each is bundled as a classic worker script into
// `Resources/workers/`; Code reads the file from its bundle and starts it from a blob URL (the
// same way it runs the AssemblyScript compiler).
const workers = {
  'editor.worker.js': 'monaco-editor/editor/editor.worker.js',
  'ts.worker.js': 'monaco-editor/language/typescript/ts.worker.js',
  'css.worker.js': 'monaco-editor/language/css/css.worker.js',
  'html.worker.js': 'monaco-editor/language/html/html.worker.js',
  'json.worker.js': 'monaco-editor/language/json/json.worker.js',
}
const wdir = join(here, '../Resources/workers')
mkdirSync(wdir, { recursive: true })
// AssemblyScript's standard library declarations feed the AssemblyScript language service. Named .txt:
// a bundle's .d.ts files are not installed (the app build skips them).
copyFileSync(join(here, '../../../node_modules/assemblyscript/std/assembly/index.d.ts'), join(wdir, 'as-std.d.txt'))
for (const [file, entry] of Object.entries(workers)) {
  const w = await build({
    stdin: { contents: `import '${entry}'`, resolveDir: join(here, '../../..'), loader: 'js' },
    bundle: true,
    write: false,
    format: 'iife',
    target: 'es2022',
    platform: 'browser',
    minify: true,
    logLevel: 'warning',
    loader: { '.ttf': 'empty' },
  })
  const text = `/* GENERATED by tools/generate.mjs — do not edit. Monaco language worker (${entry}). */\n${w.outputFiles[0].text}`
  writeFileSync(join(wdir, file), text)
  console.log(`${file}: ${(text.length / 1e6).toFixed(2)} MB`)
}

// ---- Mermaid -----------------------------------------------------------------------------------
// Diagrams for the Mermaid and Markdown previews. A large library, so it is not part of the app's
// script: `Resources/lib/mermaid.js` is read from the bundle and run the first time a diagram is drawn.
{
  const libDir = join(here, '../Resources/lib')
  mkdirSync(libDir, { recursive: true })
  const m = await build({
    stdin: { contents: "import mermaid from 'mermaid'\nglobalThis.__mermaid = mermaid", resolveDir: join(here, '../../..'), loader: 'js' },
    bundle: true,
    write: false,
    format: 'iife',
    target: 'es2022',
    platform: 'browser',
    minify: true,
    logLevel: 'error',
    define: { 'process.env.NODE_ENV': '"production"' },
  })
  const text = `/* GENERATED by tools/generate.mjs — do not edit. Mermaid, run on demand by the Mermaid and Markdown previews. */\n${m.outputFiles[0].text}`
  writeFileSync(join(libDir, 'mermaid.js'), text)
  console.log(`mermaid.js: ${(text.length / 1e6).toFixed(2)} MB`)
}
